		'post_author'  => 1,
	);
	if ( $ex ) { $data['ID'] = $ex->ID; $id = wp_update_post( $data, true ); }
	else { $id = wp_insert_post( $data, true ); }
	if ( is_wp_error( $id ) || ! $id ) { echo "FAIL {$a['slug']}\n"; continue; }
	update_post_meta( $id, 'rank_math_title', $a['meta_title'] );
	update_post_meta( $id, 'rank_math_description', $a['meta_desc'] );
